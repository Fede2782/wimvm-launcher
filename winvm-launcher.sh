choose_share_folder() {
    local docs choice custom
    docs=$(documents_dir)
    echo
    echo "Shared folder (visible in Windows as \\\\tsclient\\<name>):"
    echo "  1) Documents folder   ($docs)"
    echo "  2) Pick another existing folder"
    echo "  3) Create a new folder"
    echo "  4) No shared folder"
    [[ -n $SHARE_DIR ]] && echo "  Current: $SHARE_DIR"
    ask choice "Choice" "1"
    case $choice in
        1) SHARE_DIR=$docs ;;
        2) ask custom "Folder path" "${SHARE_DIR:-$HOME}"
           custom=${custom/#\~/$HOME}
           [[ -d $custom ]] || { warn "'$custom' does not exist."; choose_share_folder; return; }
           SHARE_DIR=$custom ;;
        3) ask custom "New folder path" "$HOME/WindowsShare"
           custom=${custom/#\~/$HOME}
           mkdir -p "$custom" || die "Cannot create $custom"
           SHARE_DIR=$custom ;;
        4) SHARE_DIR="" ;;
        *) warn "Invalid choice."; choose_share_folder; return ;;
    esac
    if [[ -n $SHARE_DIR ]]; then
        mkdir -p "$SHARE_DIR"
        local n; n=$(basename "$SHARE_DIR" | tr -c 'A-Za-z0-9._\n-' '_')
        ask SHARE_NAME "Drive name shown in Windows" "${n:-Share}"
    fi
}

choose_client() {
    echo
    echo "RDP client:"
    local fr; fr=$(find_freerdp || true)
    echo "  1) Auto — KRDC (KDE) if installed, otherwise FreeRDP"
    echo "  2) KRDC      $(command -v krdc || echo '(not found)')"
    echo "  3) FreeRDP   ${fr:-(not found)}"
    local c; ask c "Choice" "1"
    case $c in 2) RDP_CLIENT=krdc ;; 3) RDP_CLIENT=freerdp ;; *) RDP_CLIENT=auto ;; esac
    if [[ -z $(resolve_client) ]]; then
        warn "No usable client found for that choice yet — install KRDC (package 'krdc') or FreeRDP."
    fi
    local ctype; read -r ctype _ < <(resolve_client)
    if [[ ${ctype-} == krdc ]]; then
        echo "KRDC: this script writes keyboard layout, audio, shared folder and resolution into KRDC's"
        echo "per-host settings. KRDC cannot read the password from stdin: it will ask once (tick the"
        echo "option to remember it in KWallet), or the script can pass it in the rdp:// URL."
        if ask_yn "Pass the stored password in the URL (visible in 'ps' to local users for a moment)?" n; then
            KRDC_PASSWORD_IN_URL=1
        else KRDC_PASSWORD_IN_URL=0; fi
    fi
}

choose_keyboard() {
    local l v det_id i e name id km sel
    read -r l v < <(detect_xkb)
    det_id=$(xkb_to_klid "$l" "$v")
    echo
    echo "Keyboard layout sent to Windows (the same layout must be installed in Windows):"
    if [[ -n $det_id ]]; then
        echo "  0) Auto-detect on every start   [detected now: ${l}${v:+ ($v)} → $det_id]"
    else
        echo "  0) Auto-detect on every start   [detection failed — not recommended]"
    fi
    i=1
    for e in "${KBD_TABLE[@]}"; do IFS='|' read -r name id km <<<"$e"; printf '  %d) %s (%s)\n' "$i" "$name" "$id"; ((i++)); done
    echo "  $i) Other (enter a Windows layout id, e.g. 0x410)"
    echo "  $((i + 1))) Send nothing (use Windows' own layout)"
    local def=0; [[ -z $det_id ]] && def=1
    [[ $KBD_LAYOUT != auto && $KBD_LAYOUT != none ]] && def=$i
    ask sel "Choice" "$def"
    if [[ $sel == 0 ]]; then KBD_LAYOUT=auto
    elif [[ $sel =~ ^[0-9]+$ ]] && ((sel >= 1 && sel < i)); then
        IFS='|' read -r name id km <<<"${KBD_TABLE[sel - 1]}"; KBD_LAYOUT=$id
    elif [[ $sel == "$i" ]]; then ask KBD_LAYOUT "Windows layout id" "0x410"
    else KBD_LAYOUT=none; fi
}

wizard() {
    local fresh=$1 old_vm=$VM_NAME old_user=$RDP_USER

    have virsh || die "'virsh' not found. Install the libvirt client tools."
    have python3 || die "'python3' is required."

    echo
    ask LIBVIRT_URI "libvirt connection URI" "$LIBVIRT_URI"
    vsh list --all --name >/dev/null 2>&1 || die "Cannot connect to $LIBVIRT_URI (is libvirtd running, are you in the 'libvirt' group?)"
    echo "Available VMs:"; vsh list --all --name 2>/dev/null | sed '/^$/d; s/^/  - /'
    local vm
    while :; do
        ask vm "VM name" "${VM_NAME:-}"
        [[ -z $vm ]] && continue
        vsh dominfo "$vm" >/dev/null 2>&1 && break
        warn "VM '$vm' not found on $LIBVIRT_URI."
    done
    VM_NAME=$vm
    vsh dumpxml "$VM_NAME" 2>/dev/null | grep -q 'org.qemu.guest_agent.0' ||
        warn "The VM has no qemu-guest-agent channel; IP detection and readiness checks will not work."

    # --- credentials ------------------------------------------------------- #
    ask RDP_USER "Windows username (use DOMAIN\\user for domain/Microsoft accounts if needed)" "$RDP_USER"
    local need_pw=0 p1 p2
    [[ $fresh == 1 || $VM_NAME != "$old_vm" || $RDP_USER != "$old_user" ]] && need_pw=1
    if ((need_pw == 0)); then ask_yn "Change the stored password?" n && need_pw=1; fi
    if ((need_pw)); then
        while :; do
            read -rsp "Windows password: " p1; echo
            read -rsp "Repeat password:  " p2; echo
            [[ -n $p1 && $p1 == "$p2" ]] && break
            warn "Passwords empty or not matching, try again."
        done
        if have secret-tool && cred_store "$RDP_USER" "$p1" 2>/dev/null; then
            CRED_BACKEND=secret-service
            info "Password stored in the desktop keyring (KWallet / Secret Service)."
        else
            warn "Could not use the Secret Service keyring (is secret-tool installed and KWallet/GNOME Keyring unlocked?)."
            if ask_yn "Store it in a file readable only by you (chmod 600) instead? Less safe." n; then
                CRED_BACKEND=file; cred_store "$RDP_USER" "$p1"
            else die "Aborted: no safe credential storage available."; fi
        fi
        if [[ -n $old_vm && ( $old_vm != "$VM_NAME" || $old_user != "$RDP_USER" ) ]]; then cred_clear "$old_vm" "$old_user"; fi
        p1=""; p2=""
    fi

    # --- behaviour --------------------------------------------------------- #
    echo
    ask IDLE_MINUTES "Suspend the VM after how many idle minutes with no RDP session? (0 = never)" "$IDLE_MINUTES"
    [[ $IDLE_MINUTES =~ ^[0-9]+$ ]] || IDLE_MINUTES=15
    echo "Suspend method:"
    echo "  1) pause        — freeze vCPUs, RAM stays used, instant resume (lost on host reboot)"
    echo "  2) managedsave  — save RAM to disk and free it, slower resume, survives host reboot"
    local m; ask m "Choice" "$([[ $SUSPEND_MODE == managedsave ]] && echo 2 || echo 1)"
    [[ $m == 2 ]] && SUSPEND_MODE=managedsave || SUSPEND_MODE=pause

    choose_share_folder
    choose_client
    choose_keyboard
    ask_yn "Open the session in a window (recommended) instead of fullscreen?" "$([[ $FULLSCREEN == 1 ]] && echo n || echo y)" && FULLSCREEN=0 || FULLSCREEN=1
    ask MENU_NAME "Application menu entry name" "$MENU_NAME"

    if ask_yn "Customise advanced options (clock sync, scaling, unicode keys, microphone, timeout)?" n; then
        ask_yn "Send typed characters as Unicode (fixes wrong keys if the Windows layout differs)?" "$([[ $KBD_UNICODE == 1 ]] && echo y || echo n)" && KBD_UNICODE=1 || KBD_UNICODE=0
        ask TIME_SYNC_AUTOFIX "Auto-start the Windows Time service if the clock sync needs it (1/0)" "$TIME_SYNC_AUTOFIX"
        ask TIME_SYNC "Sync Windows clock with the host: always / resume (only after pause) / off" "$TIME_SYNC"
        [[ $TIME_SYNC =~ ^(always|resume|off)$ ]] || TIME_SYNC=always
        ask SCALE "Display scaling %: auto / 100 / 140 / 180 ..." "$SCALE"
        ask_yn "Redirect the microphone too?" "$([[ $MICROPHONE == 1 ]] && echo y || echo n)" && MICROPHONE=1 || MICROPHONE=0
        ask READY_TIMEOUT "Max seconds to wait for VM/RDP readiness" "$READY_TIMEOUT"
        ask PASSWORD_MODE "FreeRDP password passing: stdin (safe) / arg (fallback if stdin fails)" "$PASSWORD_MODE"
    fi
    save_config
}

