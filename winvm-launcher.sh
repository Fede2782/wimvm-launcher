#!/usr/bin/env bash
# =============================================================================
# winvm-launcher — start / resume a libvirt Windows VM and open an RDP session
#
#   winvm-launcher.sh install      install menu entry, icons, ask configuration
#   winvm-launcher.sh configure    change any setting (VM, credentials, idle...)
#   winvm-launcher.sh uninstall    remove everything this script installed
#
# Internal / convenience commands (the menu entry uses these):
#   launch        make sure the VM is up, then open RDP
#   suspend       suspend the VM right now
#   status        show configuration and VM state
#   idle-watch    background watcher that suspends the VM when unused
#
# Requirements: virsh (libvirt client), python3, qemu-guest-agent inside the
# guest, secret-tool (libsecret) for credential storage, and one RDP client:
# FreeRDP (xfreerdp / sdl-freerdp, v2 or v3) or KRDC.
# =============================================================================
set -u

APP_ID="winvm-launcher"
ICON_NAME="winvm-launcher"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONF_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/$APP_ID"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/$APP_ID"
RUN_DIR="${XDG_RUNTIME_DIR:-/tmp}/$APP_ID-$(id -u)"
CONF_FILE="$CONF_DIR/config"
APP_DIR="$DATA_HOME/$APP_ID"
BIN_LINK="$HOME/.local/bin/$APP_ID"
DESKTOP_FILE="$DATA_HOME/applications/$APP_ID.desktop"
LOG_FILE="$STATE_DIR/launcher.log"
SELF_INSTALLED="$APP_DIR/$APP_ID"

# --------------------------------------------------------------------------- #
# Generic helpers
# --------------------------------------------------------------------------- #
log() { mkdir -p "$STATE_DIR"; printf '%s %s\n' "$(date '+%F %T')" "$*" >>"$LOG_FILE"; }
info() { printf '\033[1;34m::\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31mError:\033[0m %s\n' "$*" >&2; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

ask() { # ask VAR "Prompt" "default"
    local __var=$1 __prompt=$2 __def=${3-} __in
    if [[ -n $__def ]]; then read -rp "$__prompt [$__def]: " __in; else read -rp "$__prompt: " __in; fi
    printf -v "$__var" '%s' "${__in:-$__def}"
}
ask_yn() { # ask_yn "Prompt" y|n  -> exit status 0 = yes
    local def=${2:-n} in hint="y/N"
    [[ $def == y ]] && hint="Y/n"
    read -rp "$1 [$hint]: " in
    in=${in:-$def}
    [[ $in =~ ^[Yy] ]]
}

# --------------------------------------------------------------------------- #
# Configuration
# --------------------------------------------------------------------------- #
CONFIG_VARS=(LIBVIRT_URI VM_NAME RDP_USER CRED_BACKEND IDLE_MINUTES SUSPEND_MODE
             SHARE_DIR SHARE_NAME RDP_CLIENT FULLSCREEN KBD_LAYOUT SCALE MENU_NAME
             READY_TIMEOUT RDP_PORT MICROPHONE PASSWORD_MODE KRDC_PASSWORD_IN_URL KBD_UNICODE TIME_SYNC TIME_SYNC_AUTOFIX)

set_defaults() {
    : "${LIBVIRT_URI:=qemu:///system}"
    : "${VM_NAME:=}"
    : "${RDP_USER:=}"
    : "${CRED_BACKEND:=secret-service}"   # secret-service | file
    : "${IDLE_MINUTES:=15}"               # 0 = never suspend
    : "${SUSPEND_MODE:=pause}"            # pause | managedsave
    : "${SHARE_DIR:=}"
    : "${SHARE_NAME:=Share}"
    : "${RDP_CLIENT:=auto}"               # auto | freerdp | krdc | /path/to/binary
    : "${FULLSCREEN:=0}"
    : "${KBD_LAYOUT:=auto}"               # auto | none | 0x0410 ...
    : "${SCALE:=auto}"                    # auto | 100 | 140 | 180 ...
    : "${MENU_NAME:=Windows VM}"
    : "${READY_TIMEOUT:=300}"
    : "${RDP_PORT:=3389}"
    : "${MICROPHONE:=1}"
    : "${PASSWORD_MODE:=stdin}"           # stdin (not visible in ps) | arg (fallback)
    : "${KRDC_PASSWORD_IN_URL:=0}"
    : "${TIME_SYNC_AUTOFIX:=1}"           # 1 = start/enable the Windows Time service if qga needs it
    : "${TIME_SYNC:=always}"               # always | resume | off  (host → guest clock via qemu-ga)
    : "${KBD_UNICODE:=0}"                 # 1 = send typed characters instead of scancodes
}

load_config() {
    set_defaults
    if [[ -r $CONF_FILE ]]; then
        # shellcheck disable=SC1090
        source "$CONF_FILE"
        set_defaults
    else
        return 1
    fi
}

save_config() {
    mkdir -p "$CONF_DIR"; chmod 700 "$CONF_DIR"
    {
        echo "# Generated by $APP_ID — edit with: $APP_ID configure"
        local v
        for v in "${CONFIG_VARS[@]}"; do printf '%s=%q\n' "$v" "${!v}"; done
    } >"$CONF_FILE"
    chmod 600 "$CONF_FILE"
}

# LC_ALL=C: virsh output (domstate, dominfo...) is translated otherwise, e.g. "in esecuzione"
vsh() { LC_ALL=C LANG=C virsh -c "$LIBVIRT_URI" "$@"; }

# --------------------------------------------------------------------------- #
# Credential storage
#   secret-service : libsecret → KWallet (KDE) / GNOME Keyring, encrypted
#   file           : chmod 600 plain-text file (only if the user insists)
# --------------------------------------------------------------------------- #
cred_store() { # user password
    case $CRED_BACKEND in
        secret-service)
            printf '%s' "$2" | secret-tool store --label="$MENU_NAME ($VM_NAME / $1)" \
                service "$APP_ID" vm "$VM_NAME" user "$1" ;;
        file)
            ( umask 077; printf '%s' "$2" >"$CONF_DIR/password" ) ;;
    esac
}
cred_get() {
    case $CRED_BACKEND in
        secret-service) secret-tool lookup service "$APP_ID" vm "$VM_NAME" user "$RDP_USER" ;;
        file) cat "$CONF_DIR/password" 2>/dev/null ;;
    esac
}
cred_clear() { # vm user
    have secret-tool && secret-tool clear service "$APP_ID" vm "$1" user "$2" 2>/dev/null
    rm -f "$CONF_DIR/password"
}

# --------------------------------------------------------------------------- #
# Desktop notifications / dialogs / progress bar
# --------------------------------------------------------------------------- #
notify() { # title body
    have notify-send && notify-send -a "$APP_ID" -i "$ICON_NAME" "$1" "${2-}" 2>/dev/null
    log "notify: $1 ${2-}"
}
error_dialog() {
    if have kdialog; then kdialog --title "$MENU_NAME" --error "$1" 2>/dev/null
    elif have zenity; then zenity --error --title "$MENU_NAME" --text "$1" 2>/dev/null
    else notify "$MENU_NAME" "$1"; fi
}

PROG_SVC=""; PROG_PATH=""; QDBUS=""
progress_start() { # text steps
    QDBUS=$(command -v qdbus6 || command -v qdbus-qt6 || command -v qdbus || command -v qdbus-qt5 || true)
    if [[ -n $QDBUS ]] && have kdialog; then
        local ref
        ref=$(kdialog --title "$MENU_NAME" --progressbar "$1" "$2" 2>/dev/null) || ref=""
        read -r PROG_SVC PROG_PATH <<<"$ref"
    fi
    [[ -z $PROG_SVC ]] && notify "$MENU_NAME" "$1"
}
progress_set() { # value label
    if [[ -n $PROG_SVC ]]; then
        "$QDBUS" "$PROG_SVC" "$PROG_PATH" org.kde.kdialog.ProgressDialog.value "$1" >/dev/null 2>&1
        "$QDBUS" "$PROG_SVC" "$PROG_PATH" org.kde.kdialog.ProgressDialog.setLabelText "$2" >/dev/null 2>&1
    fi
    log "progress $1: $2"
}
progress_close() {
    [[ -n $PROG_SVC ]] && "$QDBUS" "$PROG_SVC" "$PROG_PATH" org.kde.kdialog.ProgressDialog.close >/dev/null 2>&1
    PROG_SVC=""
}

fail() {
    progress_close
    log "FAIL: $*"
    error_dialog "$*"
    exit 1
}

# --------------------------------------------------------------------------- #
# VM control
# --------------------------------------------------------------------------- #
vm_state() { vsh domstate "$VM_NAME" 2>/dev/null | head -n1 | tr -d '\r'; }
vm_has_managed_save() { vsh dominfo "$VM_NAME" 2>/dev/null | grep -qiE '^Managed save:\s+yes'; }

# Brings the domain to "running". Sets NEEDS_TIME_SYNC=1 when it was resumed.
NEEDS_TIME_SYNC=0
ensure_vm_running() {
    local state i
    state=$(vm_state)
    [[ -z $state ]] && fail "Cannot query VM '$VM_NAME' on $LIBVIRT_URI. Is libvirt reachable and are you in the 'libvirt' group?"
    log "VM state: $state"
    case $state in
        running) ;;
        paused)
            progress_set 1 "Resuming paused VM…"
            vsh resume "$VM_NAME" >>"$LOG_FILE" 2>&1 || fail "Could not resume VM '$VM_NAME' (see $LOG_FILE)."
            NEEDS_TIME_SYNC=1 ;;
        pmsuspended)
            progress_set 1 "Waking VM from guest sleep…"
            vsh dompmwakeup "$VM_NAME" >>"$LOG_FILE" 2>&1 || fail "Could not wake VM '$VM_NAME'."
            NEEDS_TIME_SYNC=1 ;;
        "shut off"|"in shutdown")
            if [[ $state == "in shutdown" ]]; then
                progress_set 1 "Waiting for VM to finish shutting down…"
                for ((i = 0; i < 60; i++)); do [[ $(vm_state) == "shut off" ]] && break; sleep 2; done
            fi
            vm_has_managed_save && NEEDS_TIME_SYNC=1
            progress_set 1 "Starting VM…"
            vsh start "$VM_NAME" >>"$LOG_FILE" 2>&1 || fail "Could not start VM '$VM_NAME' (see $LOG_FILE)."
            ;;
        *) fail "VM '$VM_NAME' is in unsupported state '$state'." ;;
    esac
}

# Sets the Windows clock from the host clock through the guest agent (guest-set-time).
# "always": on every launch; "resume": only after pause/sleep/restore; "off": never.
# Runs a program inside the guest through the agent (guest-exec) and waits for it.
# Returns the guest exit code (or 255 if the agent call itself failed).
guest_run() { # exe args...
    local json out pid st i
    json=$(python3 -c 'import json, sys
print(json.dumps({"execute": "guest-exec", "arguments": {"path": sys.argv[1], "arg": sys.argv[2:], "capture-output": True}}))' "$@")
    out=$(vsh qemu-agent-command "$VM_NAME" "$json" --timeout 10 2>>"$LOG_FILE") || return 255
    pid=$(python3 -c 'import sys, json; print(json.load(sys.stdin)["return"]["pid"])' <<<"$out" 2>/dev/null) || return 255
    for ((i = 0; i < 30; i++)); do
        st=$(vsh qemu-agent-command "$VM_NAME" "{\"execute\":\"guest-exec-status\",\"arguments\":{\"pid\":$pid}}" --timeout 10 2>/dev/null) || return 255
        if python3 -c 'import sys, json; sys.exit(0 if json.load(sys.stdin)["return"].get("exited") else 1)' <<<"$st" 2>/dev/null; then
            python3 -c 'import sys, json; print(json.load(sys.stdin)["return"].get("exitcode", 0))' <<<"$st"
            return 0
        fi
        sleep 1
    done
    return 255
}

# qemu-ga on Windows refuses guest-set-time when the "Windows Time" service is not running.
fix_w32time() {
    log "starting/enabling the Windows Time service in the guest"
    guest_run 'C:\Windows\System32\cmd.exe' /c 'sc config w32time start= auto & net start w32time' >>"$LOG_FILE" 2>&1
}

# Sets the Windows clock from the host clock through the guest agent (guest-set-time).
# "always": on every launch; "resume": only after pause/sleep/restore; "off": never.
sync_guest_time() {
    case $TIME_SYNC in
        always) ;;
        resume) ((NEEDS_TIME_SYNC)) || return 0 ;;
        *) return 0 ;;
    esac
    progress_set 3 "Synchronising the Windows clock with the host…"
    local out
    # Preferred: send the exact host time (ns since epoch, UTC) — Windows applies it directly
    out=$(vsh qemu-agent-command "$VM_NAME" "{\"execute\":\"guest-set-time\",\"arguments\":{\"time\":$(date +%s%N)}}" --timeout 10 2>&1) &&
        { log "guest clock set from host time"; return 0; }
    log "explicit clock set failed: $out"
    # Fallback: ask the guest to resync from its RTC (needs the Windows Time service)
    out=$(vsh domtime "$VM_NAME" --sync 2>&1) && { log "guest clock synchronised with host (domtime --sync)"; return 0; }
    log "clock sync failed: $out"
    if [[ $TIME_SYNC_AUTOFIX == 1 && $out == *"Windows Time service not running"* ]]; then
        fix_w32time
        sleep 2
        if out=$(vsh domtime "$VM_NAME" --sync 2>&1); then
            log "guest clock synchronised with host (after starting the Windows Time service)"
            return 0
        fi
        log "clock sync still failing: $out"
    fi
    notify "$MENU_NAME" "Could not sync the Windows clock (see $LOG_FILE)."
}

wait_for_agent() {
    local deadline=$((SECONDS + READY_TIMEOUT)) out
    while ((SECONDS < deadline)); do
        out=$(vsh qemu-agent-command "$VM_NAME" '{"execute":"guest-ping"}' --timeout 5 2>/dev/null) || out=""
        [[ $out == *'"return"'* ]] && return 0
        sleep 2
    done
    return 1
}

guest_ips() {
    vsh qemu-agent-command "$VM_NAME" '{"execute":"guest-network-get-interfaces"}' --timeout 5 2>/dev/null |
    python3 -c '
import sys, json
try:
    data = json.load(sys.stdin)["return"]
except Exception:
    sys.exit(1)
for itf in data:
    if itf.get("name", "").lower().startswith(("lo", "loopback")):
        continue
    for a in itf.get("ip-addresses", []):
        if a.get("ip-address-type") != "ipv4":
            continue
        ip = a["ip-address"]
        if ip.startswith(("127.", "169.254.")):
            continue
        print(ip)
'
}

tcp_open() { timeout 2 bash -c "exec 3<>/dev/tcp/$1/$2" 2>/dev/null; }

# Sets RDP_HOST once guest agent answers AND the RDP port accepts connections.
wait_for_rdp() {
    local deadline=$((SECONDS + READY_TIMEOUT)) ip
    RDP_HOST=""
    while ((SECONDS < deadline)); do
        while read -r ip; do
            [[ -z $ip ]] && continue
            if tcp_open "$ip" "$RDP_PORT"; then RDP_HOST=$ip; return 0; fi
        done < <(guest_ips)
        sleep 2
    done
    return 1
}

do_suspend() {
    [[ $(vm_state) == running ]] || return 0
    case $SUSPEND_MODE in
        managedsave) vsh managedsave "$VM_NAME" >>"$LOG_FILE" 2>&1 ;;
        *)           vsh suspend "$VM_NAME" >>"$LOG_FILE" 2>&1 ;;
    esac && notify "$MENU_NAME" "VM suspended (idle)."
}

# --------------------------------------------------------------------------- #
# Idle watcher: suspends the VM when nobody is connected to its RDP port
# --------------------------------------------------------------------------- #
rdp_connections() {
    local ip; ip=$(cat "$RUN_DIR/host" 2>/dev/null || true)
    ss -Htn state established 2>/dev/null | awk -v ip="$ip" -v port="$RDP_PORT" '
        { if (ip != "" ? $4 == ip ":" port : $4 ~ (":" port "$")) n++ }
        END { print n + 0 }'
}

cancel_watcher() {
    local pid
    pid=$(cat "$RUN_DIR/watcher.pid" 2>/dev/null) || return 0
    if [[ -n $pid ]] && grep -qa 'idle-watch' "/proc/$pid/cmdline" 2>/dev/null; then
        kill -- "-$pid" 2>/dev/null || kill "$pid" 2>/dev/null
    fi
    rm -f "$RUN_DIR/watcher.pid"
}

cmd_idle_watch() {
    load_config || exit 1
    ((IDLE_MINUTES > 0)) || exit 0
    mkdir -p "$RUN_DIR"; echo $$ >"$RUN_DIR/watcher.pid"
    local idle_since=$SECONDS limit=$((IDLE_MINUTES * 60))
    log "idle watcher started (${IDLE_MINUTES} min)"
    while :; do
        sleep 20
        [[ $(vm_state) == running ]] || break
        if (($(rdp_connections) > 0)); then idle_since=$SECONDS; continue; fi
        if ((SECONDS - idle_since >= limit)); then
            log "idle limit reached, suspending ($SUSPEND_MODE)"
            do_suspend; break
        fi
    done
    rm -f "$RUN_DIR/watcher.pid"
}

# --------------------------------------------------------------------------- #
# Host detection: keyboard layout, scaling, shared folder
# --------------------------------------------------------------------------- #
detect_xkb() { # prints "layout variant"; also sets DETECT_SOURCE
    local l="" v="" kr q
    DETECT_SOURCE=""
    # 1) KDE: layout that is active right now (works on Wayland and X11)
    q=$(command -v qdbus6 || command -v qdbus-qt6 || command -v qdbus || command -v qdbus-qt5 || true)
    if [[ -n $q ]]; then
        # getLayout returns the INDEX of the active layout in the configured list
        local idx kl kv; idx=$("$q" org.kde.keyboard /Layouts org.kde.KeyboardLayouts.getLayout 2>/dev/null | head -n1)
        kr=$(command -v kreadconfig6 || command -v kreadconfig5 || true)
        if [[ $idx =~ ^[0-9]+$ && -n $kr ]]; then
            kl=$("$kr" --file kxkbrc --group Layout --key LayoutList 2>/dev/null)
            kv=$("$kr" --file kxkbrc --group Layout --key VariantList 2>/dev/null)
            l=$(cut -d, -f$((idx + 1)) <<<"$kl")
            v=$(cut -d, -f$((idx + 1)) <<<"$kv")
            [[ -n $l ]] && DETECT_SOURCE="kde-dbus"
        fi
    fi
    # 2) KDE configuration file
    if [[ -z $l ]]; then
        kr=$(command -v kreadconfig6 || command -v kreadconfig5 || true)
        if [[ -n $kr ]]; then
            l=$("$kr" --file kxkbrc --group Layout --key LayoutList 2>/dev/null)
            v=$("$kr" --file kxkbrc --group Layout --key VariantList 2>/dev/null)
            [[ -n $l ]] && DETECT_SOURCE="kxkbrc"
        fi
    fi
    # 3) GNOME
    if [[ -z $l ]] && have gsettings; then
        l=$(gsettings get org.gnome.desktop.input-sources sources 2>/dev/null | sed -n "s/.*('xkb', '\([a-z]*\)\(+\([^']*\)\)\{0,1\}').*/\1/p")
        [[ -n $l ]] && DETECT_SOURCE="gsettings"
    fi
    # 4) system-wide X11 layout (what the login screen uses)
    if [[ -z $l ]] && have localectl; then
        l=$(localectl status 2>/dev/null | awk -F': *' '/X11 Layout/{print $2}')
        v=$(localectl status 2>/dev/null | awk -F': *' '/X11 Variant/{print $2}')
        [[ $l == "n/a" ]] && { l=""; v=""; }
        [[ -n $l ]] && DETECT_SOURCE="localectl"
    fi
    # 5) setxkbmap only on a real X11 session (on Wayland it reports XWayland's default "us")
    if [[ -z $l && ${XDG_SESSION_TYPE-} != wayland ]] && have setxkbmap; then
        l=$(setxkbmap -query 2>/dev/null | awk '/^layout:/{print $2}')
        v=$(setxkbmap -query 2>/dev/null | awk '/^variant:/{print $2}')
        [[ -n $l ]] && DETECT_SOURCE="setxkbmap"
    fi
    # 6) console keymap, then language/country of the locale
    if [[ -z $l && -r /etc/vconsole.conf ]]; then
        l=$(awk -F= '/^KEYMAP=/{gsub(/"/,"",$2); print $2}' /etc/vconsole.conf | sed 's/[0-9]*$//')
        [[ -n $l ]] && DETECT_SOURCE="vconsole"
    fi
    if [[ -z $l && -n ${LANG-} ]]; then
        l=$(sed 's/^[a-z]*_\([A-Z]*\).*/\1/' <<<"$LANG" | tr 'A-Z' 'a-z')
        [[ -n $l ]] && DETECT_SOURCE="locale"
    fi
    [[ $v == "n/a" ]] && v=""
    l=${l%%,*}
    # sanity: a layout code is letters only (rejects things like "0")
    [[ $l =~ ^[a-z]{2,}$ ]] || { l=""; v=""; DETECT_SOURCE=""; }
    echo "$l ${v%%,*}"
}

xkb_to_klid() { # layout variant -> Windows keyboard layout id (empty if unknown)
    local l=$1 v=${2-}
    case $l in
        us) [[ $v == intl || $v == altgr-intl ]] && echo 0x20409 || echo 0x409 ;;
        gb) echo 0x809 ;;   ie) echo 0x1809 ;;  it) echo 0x410 ;;
        de) echo 0x407 ;;   at) echo 0xc07 ;;
        ch) [[ $v == fr ]] && echo 0x100c || echo 0x807 ;;
        fr) echo 0x40c ;;   be) echo 0x813 ;;   es) echo 0x40a ;;  latam) echo 0x80a ;;
        pt) echo 0x816 ;;   br) echo 0x416 ;;   nl) echo 0x413 ;;
        se) echo 0x41d ;;   no) echo 0x414 ;;   dk) echo 0x406 ;;  fi) echo 0x40b ;;
        is) echo 0x40f ;;   pl) echo 0x415 ;;   cz) echo 0x405 ;;  sk) echo 0x41b ;;
        hu) echo 0x40e ;;   ro) echo 0x418 ;;   bg) echo 0x402 ;;  hr) echo 0x41a ;;
        si) echo 0x424 ;;   ru) echo 0x419 ;;   ua) echo 0x422 ;;  gr) echo 0x408 ;;
        tr) echo 0x41f ;;   il) echo 0x40d ;;   jp) echo 0x411 ;;  kr) echo 0x412 ;;
        *)  echo "" ;;
    esac
}

# name|Windows layout id|KRDC keymap
KBD_TABLE=(
    "Italiano|0x410|it"
    "English (US)|0x409|en-us"
    "English (US, International)|0x20409|en-us"
    "English (UK)|0x809|en-gb"
    "Deutsch|0x407|de"
    "Deutsch (Schweiz)|0x807|de-ch"
    "Français (Suisse)|0x100c|fr-ch"
    "Français|0x40c|fr"
    "Español|0x40a|es"
    "Português|0x816|pt"
    "Português (Brasil)|0x416|pt-br"
    "Nederlands|0x413|nl"
    "Svenska|0x41d|sv"
    "Polski|0x415|pl"
    "Русский|0x419|ru"
    "Türkçe|0x41f|tr"
)
# order of KRDC's own keyboard list (value stored in krdcrc is the index)
KRDC_KEYMAPS=(ar cs da de de-ch en-dv en-gb en-us es et fi fo fr fr-be fr-ca fr-ch he hr hu is it ja ko lt lv mk nl nl-be no pl pt pt-br ru sl sv th tr)

klid_to_krdc() { # Windows id -> KRDC keymap name (default en-us)
    local e; for e in "${KBD_TABLE[@]}"; do
        IFS='|' read -r _ id km <<<"$e"
        [[ ${id,,} == "${1,,}" ]] && { echo "$km"; return; }
    done
    echo "en-us"
}
krdc_keymap_index() { local i; for i in "${!KRDC_KEYMAPS[@]}"; do [[ ${KRDC_KEYMAPS[$i]} == "$1" ]] && { echo "$i"; return; }; done; echo 7; }

host_kbd_layout() {
    case $KBD_LAYOUT in
        none) echo "" ;;
        auto) local l v; read -r l v < <(detect_xkb); xkb_to_klid "$l" "$v" ;;
        *)    echo "$KBD_LAYOUT" ;;
    esac
}

host_scale_percent() {
    if [[ $SCALE != auto ]]; then echo "$SCALE"; return; fi
    have kscreen-doctor || { echo 100; return; }
    kscreen-doctor -j 2>/dev/null | python3 -c '
import sys, json
try:
    outs = [o for o in json.load(sys.stdin)["outputs"] if o.get("enabled")]
    outs.sort(key=lambda o: o.get("priority", 99))
    print(int(round(outs[0].get("scale", 1.0) * 100)) if outs else 100)
except Exception:
    print(100)
'
}

documents_dir() {
    local d=""
    have xdg-user-dir && d=$(xdg-user-dir DOCUMENTS 2>/dev/null)
    if [[ -z $d || $d == "$HOME" || $d == "$HOME/" ]]; then
        d=$(sed -n 's/^XDG_DOCUMENTS_DIR="\(.*\)"/\1/p' "${XDG_CONFIG_HOME:-$HOME/.config}/user-dirs.dirs" 2>/dev/null | sed "s|\$HOME|$HOME|")
    fi
    [[ -z $d ]] && d="$HOME/Documents"
    echo "$d"
}

# --------------------------------------------------------------------------- #
# RDP client
# --------------------------------------------------------------------------- #
FREERDP_CANDIDATES=(sdl-freerdp3 xfreerdp3 wlfreerdp3 sdl-freerdp xfreerdp wlfreerdp)
find_freerdp() { local b; for b in "${FREERDP_CANDIDATES[@]}"; do have "$b" && { command -v "$b"; return 0; }; done; return 1; }
freerdp_major() {
    local m; m=$("$1" /version 2>&1 | grep -oE 'version [0-9]+' | head -n1 | grep -oE '[0-9]+')
    [[ -z $m ]] && { [[ $1 == *3 ]] && m=3 || m=2; }
    echo "$m"
}

resolve_client() { # prints "type path"
    case $RDP_CLIENT in
        freerdp) local p; p=$(find_freerdp) && echo "freerdp $p" ;;
        krdc)    have krdc && echo "krdc $(command -v krdc)" ;;
        auto)    local p; if have krdc; then echo "krdc $(command -v krdc)"
                 elif p=$(find_freerdp); then echo "freerdp $p"; fi ;;
        /*)      [[ -x $RDP_CLIENT ]] && { [[ $RDP_CLIENT == *krdc* ]] && echo "krdc $RDP_CLIENT" || echo "freerdp $RDP_CLIENT"; } ;;
    esac
}

urlencode() { python3 -c 'import sys, urllib.parse as u; print(u.quote(sys.argv[1], safe=""))' "$1"; }

# KRDC has no command-line switches, but it reads per-host settings from krdcrc.
# Keys/values follow KRDC's RdpHostPreferences (keyboardLayout = index, sound 0 = local,
# resolution 3 = "match window", shareMedia = shared directory).
krdc_write_prefs() { # host
    local kw; kw=$(command -v kwriteconfig6 || command -v kwriteconfig5 || true)
    [[ -z $kw ]] && { log "krdc: kwriteconfig not found, per-host settings not written"; return 0; }
    local klid idx g
    klid=$(host_kbd_layout); idx=$(krdc_keymap_index "$(klid_to_krdc "${klid:-0x409}")")
    for g in "rdp://$1" "rdp://$1:$RDP_PORT" "rdp://$RDP_USER@$1" "rdp://$RDP_USER@$1:$RDP_PORT"; do
        local -a base=("$kw" --file krdcrc --group hostpreferences --group "$g")
        "${base[@]}" --key keyboardLayout "$idx"
        "${base[@]}" --key sound 0
        "${base[@]}" --key resolution 3
        "${base[@]}" --key scaleToSize --type bool true
        [[ -n $SHARE_DIR && -d $SHARE_DIR ]] && "${base[@]}" --key shareMedia "$SHARE_DIR"
    done
    log "krdc: wrote per-host settings (keymap index $idx, share '$SHARE_DIR')"
}

launch_client() { # uses RDP_HOST
    local ctype cpath pw
    read -r ctype cpath < <(resolve_client)
    [[ -z ${ctype-} ]] && fail "No RDP client found. Install FreeRDP (xfreerdp / sdl-freerdp) or KRDC, then run: $APP_ID configure"
    pw=$(cred_get) || pw=""
    [[ -z $pw ]] && fail "No stored password found. Run: $APP_ID configure"
    log "client: $ctype ($cpath) → $RDP_HOST:$RDP_PORT"

    if [[ $ctype == krdc ]]; then
        local url="rdp://$(urlencode "$RDP_USER")"
        [[ $KRDC_PASSWORD_IN_URL == 1 ]] && url+=":$(urlencode "$pw")"
        url+="@$RDP_HOST:$RDP_PORT"
        krdc_write_prefs "$RDP_HOST"
        local -a kargs=()
        [[ $FULLSCREEN == 1 ]] && kargs+=(--fullscreen)
        "$cpath" "${kargs[@]}" "$url" 9>&- >>"$LOG_FILE" 2>&1
        return
    fi

    local major user domain="" pct
    major=$(freerdp_major "$cpath")
    user=$RDP_USER
    if [[ $user == *\\* ]]; then domain=${user%%\\*}; user=${user#*\\}; fi

    local -a args=("/v:$RDP_HOST:$RDP_PORT" "/u:$user" "+clipboard" "+auto-reconnect"
                   "/dynamic-resolution" "/title:$MENU_NAME")
    [[ -n $domain ]] && args+=("/d:$domain")
    if ((major >= 3)); then
        args+=("/cert:ignore" "/sound")
        [[ $MICROPHONE == 1 ]] && args+=("/microphone")
    else
        args+=("/cert-ignore" "/sound:sys:pulse")
        [[ $MICROPHONE == 1 ]] && args+=("/microphone:sys:pulse")
    fi

    # Shared folder → \\tsclient\<SHARE_NAME> inside Windows
    [[ -n $SHARE_DIR && -d $SHARE_DIR ]] && args+=("/drive:$SHARE_NAME,$SHARE_DIR")

    # Host keyboard layout
    local klid; klid=$(host_kbd_layout)
    if [[ -n $klid ]]; then
        if ((major >= 3)); then
            local kopt="/kbd:layout:$klid,lang:$klid"
            [[ $KBD_UNICODE == 1 ]] && kopt+=",unicode:on"
            args+=("$kopt")
        else
            args+=("/kbd:$klid" "/kbd-lang:$klid")
            [[ $KBD_UNICODE == 1 ]] && args+=("/kbd-unicode")
        fi
    else
        log "keyboard: no Windows layout id for host layout '$(detect_xkb)' (set KBD_LAYOUT via configure)"
    fi

    # Window size + HiDPI scaling
    if [[ $FULLSCREEN == 1 ]]; then args+=("/f")
    elif ((major >= 3)); then args+=("/size:90%")
    else args+=("/w:1600" "/h:900"); fi
    pct=$(host_scale_percent)
    if [[ $pct =~ ^[0-9]+$ ]] && ((pct > 100)); then
        local dev=100; ((pct >= 120)) && dev=140; ((pct >= 160)) && dev=180
        args+=("/scale-desktop:$pct" "/scale-device:$dev")
    fi

    log "freerdp v$major args: ${args[*]}"
    if [[ $PASSWORD_MODE == arg ]]; then
        "$cpath" "${args[@]}" "/p:$pw" 9>&- >>"$LOG_FILE" 2>&1
    else
        # password goes through stdin → never visible in the process list
        printf '%s\n' "$pw" | "$cpath" "${args[@]}" "/from-stdin:force" 9>&- >>"$LOG_FILE" 2>&1
    fi
}

