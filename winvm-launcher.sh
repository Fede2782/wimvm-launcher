cmd_launch() {
    load_config || fail "Not configured. Run: $APP_ID install"
    mkdir -p "$RUN_DIR" "$STATE_DIR"
    exec 9>"$RUN_DIR/launch.lock"
    if ! flock -n 9; then notify "$MENU_NAME" "Already starting or running."; exit 0; fi
    trap 'progress_close' EXIT
    cancel_watcher

    progress_start "Preparing $VM_NAME…" 5
    NEEDS_TIME_SYNC=0
    ensure_vm_running

    progress_set 2 "Waiting for the guest agent (Windows is booting/resuming)…"
    wait_for_agent || fail "Timed out waiting for the QEMU guest agent in '$VM_NAME'. Is qemu-guest-agent installed in Windows?"
    sync_guest_time

    progress_set 4 "Detecting the VM IP address…"
    progress_set 4 "Waiting for the Remote Desktop service…"
    wait_for_rdp || fail "Timed out waiting for RDP on '$VM_NAME'. Is Remote Desktop enabled in Windows?"
    echo "$RDP_HOST" >"$RUN_DIR/host"

    progress_set 5 "Connecting to $RDP_HOST…"
    progress_close
    launch_client
    log "client exited"

    # Client closed → start the idle timer in a detached process (without our lock fd)
    if ((IDLE_MINUTES > 0)); then
        setsid -f "$SELF_INSTALLED" idle-watch 9>&- >/dev/null 2>&1 </dev/null
    fi
}

cmd_suspend() { load_config || die "Not configured."; cancel_watcher; do_suspend; }

cmd_status() {
    load_config || die "Not configured."
    local v
    for v in "${CONFIG_VARS[@]}"; do printf '%-22s %s\n' "$v" "${!v}"; done
    echo "VM state:              $(vm_state)"
    local det; det=$(detect_xkb); detect_xkb >/dev/null   # 2nd call runs in this shell to get DETECT_SOURCE
    echo "Detected kbd layout:   '$det' (source: ${DETECT_SOURCE:-none}) → Windows id: '$(host_kbd_layout)'"
    echo "Detected scale:        $(host_scale_percent)%"
    echo "RDP client:            $(resolve_client || true)"
}

