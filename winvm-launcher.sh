in_terminal_cmd() { # used by the "Configure…" menu action
    local t
    for t in konsole gnome-terminal xfce4-terminal xterm; do
        if have "$t"; then
            case $t in
                gnome-terminal) echo "gnome-terminal -- $SELF_INSTALLED configure" ;;
                *)              echo "$t -e $SELF_INSTALLED configure" ;;
            esac
            return
        fi
    done
    echo "$SELF_INSTALLED configure"
}

write_desktop_file() {
    mkdir -p "$(dirname "$DESKTOP_FILE")"
    cat >"$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Version=1.0
Name=$MENU_NAME
GenericName=Windows virtual machine
Comment=Start or resume the Windows VM and connect through Remote Desktop
Exec="$SELF_INSTALLED" launch
Icon=$ICON_NAME
Terminal=false
Categories=System;Network;RemoteAccess;
Keywords=windows;vm;rdp;libvirt;
StartupNotify=false
Actions=suspend;configure;

[Desktop Action suspend]
Name=Suspend VM now
Exec="$SELF_INSTALLED" suspend

[Desktop Action configure]
Name=Configure…
Exec=$(in_terminal_cmd)
EOF
    chmod 644 "$DESKTOP_FILE"
}

refresh_menu() {
    have update-desktop-database && update-desktop-database "$DATA_HOME/applications" >/dev/null 2>&1
    local k; for k in kbuildsycoca6 kbuildsycoca5; do
        have "$k" && { "$k" --noincremental >/dev/null 2>&1; break; }
    done
    have gtk-update-icon-cache && gtk-update-icon-cache -qtf "$DATA_HOME/icons/hicolor" >/dev/null 2>&1
    return 0
}

cmd_install() {
    [[ $EUID -eq 0 ]] && die "Run this as your normal user, not root."
    local src; src=$(readlink -f "${BASH_SOURCE[0]}")
    have secret-tool || warn "'secret-tool' missing (package libsecret / libsecret-tools): needed for safe password storage."
    load_config >/dev/null 2>&1 && warn "Existing configuration found; its values are used as defaults."
    wizard 1

    mkdir -p "$APP_DIR" "$(dirname "$BIN_LINK")"
    install -m 755 "$src" "$SELF_INSTALLED"
    ln -sf "$SELF_INSTALLED" "$BIN_LINK"
    install_icons
    write_desktop_file
    refresh_menu

    echo
    info "Installed. Look for '$MENU_NAME' in your application menu."
    info "Re-run '$APP_ID configure' any time; remove with '$APP_ID uninstall'."
    case ":$PATH:" in *":$HOME/.local/bin:"*) ;; *) warn "$HOME/.local/bin is not in PATH; use $SELF_INSTALLED instead." ;; esac
}

cmd_configure() {
    load_config || die "Not installed yet. Run: $0 install"
    wizard 0
    write_desktop_file
    refresh_menu
    info "Configuration saved."
}

cmd_uninstall() {
    load_config >/dev/null 2>&1
    cancel_watcher
    if ask_yn "Remove the menu entry, icons and program files?" y; then
        rm -f "$DESKTOP_FILE" "$BIN_LINK"
        rm -rf "$APP_DIR"
        local s; for s in 16 24 32 48 64 128 256; do rm -f "$DATA_HOME/icons/hicolor/${s}x${s}/apps/$ICON_NAME.png"; done
        refresh_menu
        info "Program files removed."
    fi
    if ask_yn "Also delete configuration, logs and the stored password?" y; then
        [[ -n ${VM_NAME-} ]] && cred_clear "$VM_NAME" "${RDP_USER-}"
        rm -rf "$CONF_DIR" "$STATE_DIR" "$RUN_DIR"
        info "Configuration and credentials removed."
    fi
    echo "The virtual machine itself was not touched."
    if [[ -n ${VM_NAME-} ]] && [[ $(vm_state 2>/dev/null) == paused ]]; then
        ask_yn "VM '$VM_NAME' is currently paused. Resume it now?" n && vsh resume "$VM_NAME"
    fi
}

usage() { sed -n '2,16p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; }

case ${1-} in
    install)    cmd_install ;;
    configure)  cmd_configure ;;
    uninstall)  cmd_uninstall ;;
    launch)     cmd_launch ;;
    suspend)    cmd_suspend ;;
    status)     cmd_status ;;
    idle-watch) cmd_idle_watch ;;
    *)          usage; exit 1 ;;
esac
